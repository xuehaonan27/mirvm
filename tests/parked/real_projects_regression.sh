#!/usr/bin/env bash
# Regression for the real-project suite itself. Fixtures are all generated locally; no network access.
set -u
cd "$(dirname "$0")/.."

TMP=$(mktemp -d)
BACKGROUND_PIDS=()
PROCESS_TREE=()
collect_tree() {
    local parent=$1 child
    PROCESS_TREE+=("$parent")
    while read -r child; do
        [ -n "$child" ] || continue
        collect_tree "$child"
    done < <(pgrep -P "$parent" 2>/dev/null || true)
}
forget_background() {
    local completed=$1 pid remaining=()
    for pid in "${BACKGROUND_PIDS[@]}"; do
        [ "$pid" = "$completed" ] || remaining+=("$pid")
    done
    BACKGROUND_PIDS=("${remaining[@]}")
}
cleanup_regression() {
    local pid pid_file
    PROCESS_TREE=()
    for pid in "${BACKGROUND_PIDS[@]}"; do
        collect_tree "$pid"
    done
    for pid in "${BACKGROUND_PIDS[@]}"; do
        kill -TERM -- "-$pid" 2>/dev/null || true
    done
    for pid in "${PROCESS_TREE[@]}"; do
        kill -TERM "$pid" 2>/dev/null || true
    done
    for pid_file in "${CONTROL_FD_PIDS:-}" "${CONTROL_SUBSHELL_PIDS:-}"; do
        [ -n "$pid_file" ] && [ -f "$pid_file" ] || continue
        while read -r pid; do
            kill -TERM "$pid" 2>/dev/null || true
        done <"$pid_file"
    done
    sleep 0.05
    for pid in "${BACKGROUND_PIDS[@]}"; do
        kill -KILL -- "-$pid" 2>/dev/null || true
    done
    for pid in "${PROCESS_TREE[@]}"; do
        kill -KILL "$pid" 2>/dev/null || true
    done
    for pid in "${BACKGROUND_PIDS[@]}"; do
        wait "$pid" 2>/dev/null || true
    done
    for pid_file in "${CONTROL_FD_PIDS:-}" "${CONTROL_SUBSHELL_PIDS:-}"; do
        [ -n "$pid_file" ] && [ -f "$pid_file" ] || continue
        while read -r pid; do
            kill -KILL "$pid" 2>/dev/null || true
        done <"$pid_file"
    done
    chmod -R u+w "$TMP" 2>/dev/null || true
    rm -rf "$TMP"
}
trap cleanup_regression EXIT
PYTHON=${PYTHON:-$(command -v python3)}
pass=0 fail=0
ok() { pass=$((pass + 1)); echo "PASS $*"; }
bad() { fail=$((fail + 1)); echo "FAIL $*"; }

