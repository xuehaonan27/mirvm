//! Materialize owned assembly recipes without a compiler session.

use std::path::PathBuf;

use crate::lower::Error;
use crate::utils::content::fnv1a;
use crate::vm::ir;

// ===== syscall interception =====
//
// A bare `syscall` instruction in guest inline asm or global_asm is rewritten at the text
// level, since mirvm already holds all the GAS text at its generation point and never has to
// scan a binary. The rewrite turns `syscall` into an indirect-slot
// `call QWORD PTR [rip+mirvm_syscall_slot]`. The slot ships with the `.so` and is refilled
// after dlopen with the real address of the `arch::asmstub` trampoline, under the
// same discipline as the startup-phase refill. The trampoline preserves the full syscall
// contract (integer, flags, xmm, mxcsr) and lands in `os::process::mirvm_syscall_dispatch`,
// which passes through and traces.
//
// Not covered, and none of these forms is known to occur in practice: `sysenter`,
// `int $0x80`, `.byte 0x0f,0x05` written to evade the rewrite, and multiple statements or
// label prefixes on one line. Supporting them needs a concrete crate that hits them.

/// Line-level mnemonic match with leading whitespace already stripped: after `syscall` only
/// end of line, whitespace or a comment (`#` or `;`) is allowed. Multi-statement lines and
/// label prefixes are not covered.
fn is_syscall_insn_line(trimmed: &str) -> bool {
    let Some(rest) = trimmed.strip_prefix("syscall") else {
        return false;
    };
    let mut cs = rest.chars();
    match cs.next() {
        None => true,
        Some(c) => c.is_whitespace() || c == '#' || c == ';',
    }
}

/// Rewrites every `syscall` instruction line in `src` into an indirect slot call. Returns
/// whether anything was rewritten, which decides whether the slot definition is appended and
/// whether the slot is refilled after dlopen.
pub(crate) fn rewrite_syscall_text(src: &mut String) -> bool {
    let mut hit = false;
    let mut out = String::with_capacity(src.len() + 64);
    for line in src.split_inclusive('\n') {
        if is_syscall_insn_line(line.trim_start()) {
            out.push_str(crate::os_arch::syscall_asm::CALL);
            hit = true;
        } else {
            out.push_str(line);
        }
    }
    *src = out;
    if hit {
        src.push_str(crate::os_arch::syscall_asm::SLOT_DEF);
    }
    hit
}

/// Refills the syscall indirect slot after dlopen. A system library has no such symbol, so an
/// absent slot is skipped silently.
pub(crate) fn refill_syscall_slot(handle: usize) {
    let slot = crate::os::dll::sym(handle, c"mirvm_syscall_slot");
    if slot != 0 {
        unsafe {
            *(slot as *mut u64) = crate::arch::asmstub::syscall_trampoline_addr();
        }
    }
}

/// Materializes asm stubs in one batch: concatenate every wrapper text into one `.s`,
/// assemble it to a `.so` with `cc`, `dlopen` it, then `dlsym` each site by its own symbol
/// name to build the address table (bit position -> u64). Names are decoupled from bit
/// positions because the final order is only known at the end, while the name is already
/// baked into the text during lowering.
///
/// The content hash addresses the cache at `~/.cache/mirvm/asm-stubs/<hash>.so`, so a warm
/// cache makes no `cc` call at all. The `dlopen` handle is intentionally leaked: it stays
/// resident for the process lifetime, which keeps the code addresses valid. Materialization
/// happens in the load phase, where OS interaction is allowed; the returned u64 table moves
/// to the `Module` and the execution phase only reads and calls directly, preserving purity.
/// An empty site set yields an empty table at zero cost.
#[cfg(feature = "compiler")]
pub(crate) fn materialize(sites: &[ir::AsmSite]) -> Vec<u64> {
    try_materialize(sites)
        .unwrap_or_else(|error| panic!("asm-stub materialization failed: {error}"))
}

/// Fallible counterpart of [`materialize`]: reports an assembly, caching or symbol failure as
/// an `Err` instead of panicking.
pub(crate) fn try_materialize(sites: &[ir::AsmSite]) -> Result<Vec<u64>, Error> {
    if sites.is_empty() {
        return Ok(Vec::new());
    }
    let mut src = String::new();
    src.push_str("# Generated by the mirvm asm-stub factory -- do not edit by hand\n");
    for site in sites {
        src.push_str(&site.text);
    }
    // Bare `syscall` instructions become indirect slot calls. The rewrite runs before content
    // hashing, so the cache key matches the final bytes.
    rewrite_syscall_text(&mut src);
    // The assembler's own output ends with this note, and a linker that does not find it warns and
    // marks the stack executable. This text is generated, so it says so here; the note is empty and
    // this platform's format needs none, which is why the vocabulary decides what to write.
    let format = crate::native::artifact::asmtext::Vocabulary::of(crate::os::dll::OBJECT_FORMAT);
    if !src.ends_with('\n') {
        src.push('\n');
    }
    format.no_executable_stack(&mut src);

    // FNV-1a content hash: stable, so runs reuse the same cache key
    let h = fnv1a(src.as_bytes());

    let dir = crate::store::ASM_STUBS.dir();
    std::fs::create_dir_all(&dir).map_err(|e| {
        Error::io(
            format!(
                "failed to create the asm-stub cache directory `{}`",
                dir.display()
            ),
            e,
        )
    })?;
    let so: PathBuf = dir.join(format!("{h:016x}.so"));

    if !so.exists() {
        // -shared -fPIC keeps the wrapper self-contained with no external symbols, so dlsym
        // yields each site's real address after dlopen. The assembly source takes the staging
        // name of the product, so concurrent instantiation in one process cannot truncate
        // another's file.
        let tmp = crate::store::staging_path(&so);
        let mut s_path = tmp.clone().into_os_string();
        s_path.push(".s");
        let s_path = PathBuf::from(s_path);
        std::fs::write(&s_path, &src).map_err(|e| {
            Error::io(
                format!(
                    "failed to write the asm-stub temporary assembly `{}`",
                    s_path.display()
                ),
                e,
            )
        })?;
        let output = std::process::Command::new("cc")
            .args(crate::os::linker::COMMON)
            .args(crate::os::linker::ASM_STUB)
            .arg("-o")
            .arg(&tmp)
            .arg(&s_path)
            .output()
            .map_err(|e| {
                Error::assemble(format!(
                    "failed to invoke cc to assemble the asm-stub (is cc missing from PATH?): {e}"
                ))
            })?;
        let _ = std::fs::remove_file(&s_path);
        if !output.status.success() {
            let _ = std::fs::remove_file(&tmp);
            return Err(Error::assemble(format!(
                "cc failed to assemble the asm-stub (status={}):\n{}{}",
                output.status,
                String::from_utf8_lossy(&output.stdout),
                String::from_utf8_lossy(&output.stderr)
            )));
        }
        crate::store::publish(&so, &tmp).map_err(|e| {
            let _ = std::fs::remove_file(&tmp);
            Error::io(
                format!(
                    "failed to atomically publish the asm-stub .so `{}`",
                    so.display()
                ),
                e,
            )
        })?;
    }

    let c_so = std::ffi::CString::new(so.as_os_str().as_encoded_bytes()).map_err(|_| {
        Error::internal(format!(
            "asm-stub path contains a NUL byte: {}",
            so.display()
        ))
    })?;
    let handle = crate::os::dll::open_with_flags(
        &c_so,
        crate::os::dll::RTLD_NOW | crate::os::dll::RTLD_LOCAL,
    )
    .map_err(|error| {
        Error::assemble(format!(
            "cannot dlopen the asm-stub .so `{}`: {error}",
            so.display()
        ))
    })?;
    refill_syscall_slot(handle);

    sites
        .iter()
        .map(|site| -> Result<u64, Error> {
            let name = std::ffi::CString::new(&*site.name).map_err(|_| {
                Error::internal(format!(
                    "asm-stub symbol name contains a NUL byte: {:?}",
                    site.name
                ))
            })?;
            let addr = crate::os::dll::sym(handle, &name);
            if addr == 0 {
                return Err(Error::assemble(format!(
                    "failed to dlsym asm-stub `{}`",
                    site.name
                )));
            }
            Ok(addr as u64)
        })
        .collect()
}

/// First undefined symbol in the image whose name looks like a Rust mangled name
/// (`_R`/`_ZN`), which is the signal of a guest fn reference. libc and system symbols,
/// which the dynamic linker resolves, do not count.
///
/// The object is read here rather than by a tool: the tool's name, its flags and the spelling it
/// prints a symbol under are each the object format's, and this build writes two of those.
#[cfg(any(feature = "compiler", test))]
fn undefined_nonlib_symbols(so: &std::path::Path) -> Option<String> {
    let symbols = crate::native::symbol::symtab::object_undefined_symbols(
        so.to_str()?,
        crate::os::dll::OBJECT_FORMAT,
    )
    .ok()?;
    symbols
        .into_iter()
        .find(|symbol| symbol.starts_with("_R") || symbol.starts_with("_ZN"))
        .map(String::from)
}

/// Strips `//` line comments. rustc's target assembler, LLVM MC, treats `//` as a line
/// comment start while GNU as treats it as a division operator, and global_asm text comes
/// from the LLVM world: wasmtime's fiber asm carries many `//` comments that make cc error
/// out. They must be stripped before feeding GAS. Quoting is tracked, so `//` inside a
/// `"`/`'` string survives.
#[cfg(any(feature = "compiler", test))]
fn strip_slash_comments(asm: &mut String) {
    let mut out = String::with_capacity(asm.len());
    for line in asm.lines() {
        let mut in_str: Option<u8> = None;
        let mut cut = line.len();
        let b = line.as_bytes();
        let mut i = 0;
        while i + 1 < b.len() {
            match b[i] {
                q @ (b'"' | b'\'') => {
                    if in_str == Some(q) {
                        in_str = None;
                    } else if in_str.is_none() {
                        in_str = Some(q);
                    }
                }
                b'/' if b[i + 1] == b'/' && in_str.is_none() => {
                    cut = i;
                    break;
                }
                _ => {}
            }
            i += 1;
        }
        out.push_str(&line[..cut]);
        out.push('\n');
    }
    *asm = out;
}

/// `.s` -> `.so`, with a content-addressed cache and the same temp-name plus rename atomic
/// publish as the asm-stub factory. Naked fns are mixed into module-level asm and may
/// reference guest symbols, so `-nostdlib` is not usable; `-nostartfiles` keeps
/// dynamic-linker resolution, and RTLD_GLOBAL resolves guest fns named by naked `sym`
/// operands. Also used by the bin load phase to materialize dependency manifest text.
#[cfg(any(feature = "compiler", test))]
pub(crate) fn assemble(asm: &str) -> Result<Box<str>, Error> {
    // The image is usable only if the calls `crate::vm::interpose` lists can be redirected, so ask
    // the platform before building anything: one whose linker cannot express the redirection has
    // nothing to link.
    let interpose = crate::os::linker::interpose_args(crate::vm::interpose::INTERPOSED_CALLS)
        .ok_or_else(|| {
            Error::assemble(
                "cannot assemble a global-asm image: this platform's linker has no way to redirect \
                 the runtime calls the image must not reach directly"
                    .to_string(),
            )
        })?;
    // Same channel as the asm-stub factory: a bare `syscall` instruction in
    // global_asm/naked asm becomes an indirect slot call. The rewrite runs before content
    // hashing, so the cache key matches the final bytes; the slot ships with the `.so` and
    // `lower_inner` refills it when the `.so` joins required_native_libs.
    let mut asm = asm.to_string();
    strip_slash_comments(&mut asm);
    rewrite_syscall_text(&mut asm);
    // Guest text is assembled as written, so the note the toolchain appends to output of its own
    // making is appended here: without it the link warns and the stack is marked executable. It is
    // empty, and a format that has no such note writes nothing.
    let format = crate::native::artifact::asmtext::Vocabulary::of(crate::os::dll::OBJECT_FORMAT);
    if !asm.ends_with('\n') {
        asm.push('\n');
    }
    format.no_executable_stack(&mut asm);
    let dir = crate::store::GLOBAL_ASM.dir();
    std::fs::create_dir_all(&dir).map_err(|e| {
        Error::io(
            "failed to create the global-asm cache directory".to_string(),
            e,
        )
    })?;
    // The bridge is an input of this link rather than text of this image. On a platform whose link
    // binds a call to the first library that defines it the bridge has to be an image of its own,
    // or the calls in this one would keep their binding; on the other the object works either way,
    // and one shape for both keeps the two call sites from having to know which platform they are
    // on. Its name is the hash of its content, so it stands in for that content in this key.
    let bridge = crate::native::artifact::bridge::artifact(&dir, std::path::Path::new("cc"), b"")
        .map_err(|e| Error::assemble(e.to_string()))?;
    let bridge_name = bridge
        .file_name()
        .unwrap_or_default()
        .to_string_lossy()
        .into_owned();
    let mut hash_input = b"mirvm-global-asm-v4\0".to_vec();
    hash_input.extend_from_slice(asm.as_bytes());
    hash_input.push(0);
    hash_input.extend_from_slice(bridge_name.as_bytes());
    let hash = crate::utils::content::fnv1a(&hash_input);
    let so = dir.join(format!("{hash:016x}.so"));
    if so.exists() {
        return Ok(so.display().to_string().into());
    }
    let s_path = dir.join(format!("{hash:016x}.s"));
    std::fs::write(&s_path, asm).map_err(|e| Error::io("failed to write the global-asm .s", e))?;
    let tmp = crate::store::staging_path(&so);
    let status = std::process::Command::new("cc")
        .args(crate::os::linker::COMMON)
        .args(crate::os::linker::GLOBAL_ASM)
        .arg("-o")
        .arg(&tmp)
        .arg(&s_path)
        .arg(&bridge)
        .args(&interpose)
        .status()
        .map_err(|e| {
            Error::assemble(format!(
                "failed to invoke cc to assemble global-asm (is cc missing from PATH?): {e}"
            ))
        })?;
    if !status.success() {
        return Err(Error::assemble(format!(
            "cc failed to assemble global-asm (status={status})"
        )));
    }
    // Undefined-symbol audit: a symbol referenced by a global_asm/naked `sym` operand must
    // itself be machine code: another naked/global_asm symbol, a dynamic-library export, or
    // a guest fn reached through an ABS definition onto a P1 entry stub. A bare reference to
    // an undefined guest symbol would leave an unresolved entry that only blows up at
    // dlopen with a misleading diagnostic, so reject it loudly here.
    let undef = undefined_nonlib_symbols(&tmp);
    if let Some(sym) = undef {
        let _ = std::fs::remove_file(&tmp);
        return Err(Error::internal(format!(
            "global_asm/naked references undefined symbol `{sym}`: a sym operand may only \
             name a machine-code symbol (another naked/global_asm or a dynamic library), not \
             an interpreted guest fn"
        )));
    }
    crate::store::publish(&so, &tmp).map_err(|e| {
        Error::io(
            "failed to atomically publish the global-asm .so".to_string(),
            e,
        )
    })?;
    Ok(so.display().to_string().into())
}

#[cfg(test)]
mod portable_tests {
    use super::assemble;
    use crate::native::artifact::asmtext::{Region, Visibility, Vocabulary};

    #[test]
    fn owned_global_assembly_preserves_symbol_bytes() {
        let format = Vocabulary::of(crate::os::dll::OBJECT_FORMAT);
        let name = "mirvm_owned_assembly_probe";
        let mut source = String::new();
        format.open(&mut source, Region::Text { name });
        source.push_str(".balign 8\n");
        format.define_fn(&mut source, name, Visibility::Exported);
        // The symbol contains data; no architecture-specific instruction is executed.
        source.push_str(".quad 0x0123456789abcdef // an LLVM assembler comment\n");
        format.end_fn(&mut source, name);
        format.close(&mut source);
        let path = std::ffi::CString::new(assemble(&source).unwrap().as_bytes()).unwrap();
        let handle = crate::os::dll::open_with_flags(
            &path,
            crate::os::dll::RTLD_NOW | crate::os::dll::RTLD_LOCAL,
        )
        .unwrap();
        // dlsym accepts the C name; the assembler's leading underscore is format-specific.
        let symbol = std::ffi::CString::new(name).unwrap();
        let address = crate::os::dll::sym(handle, &symbol);
        assert_ne!(address, 0);
        let value = unsafe { (address as *const u64).read_unaligned() };
        unsafe { crate::os::dll::close(handle) };
        assert_eq!(value, 0x0123456789abcdef);
    }
}

#[cfg(all(test, target_arch = "x86_64"))]
mod tests {
    use super::try_materialize;
    use crate::vm::ir;

    #[test]
    fn materialized_stub_is_callable_and_writes_its_buffer() {
        let site = ir::AsmSite {
            name: "mirvm_asm_0".into(),
            text: r#"
.globl mirvm_asm_0
.type mirvm_asm_0,@function
.section .text.mirvm_asm_0,"ax",@progbits
mirvm_asm_0:
    .intel_syntax noprefix
    movabs rax, 0x0123456789abcdef
    mov QWORD PTR [rdi], rax
    ret
    .att_syntax
.size mirvm_asm_0, .-mirvm_asm_0
.text
"#
            .to_owned(),
        };
        let addrs = try_materialize(&[site]).unwrap();
        let mut value = 0u64;
        let stub: unsafe extern "C" fn(*mut u8) = unsafe { std::mem::transmute(addrs[0]) };
        unsafe { stub((&mut value as *mut u64).cast()) };
        assert_eq!(value, 0x0123_4567_89ab_cdef);
    }

    #[test]
    fn concurrent_materialization_of_one_hash_is_safe() {
        let name = format!("mirvm_asm_parallel_{}", std::process::id());
        let site = ir::AsmSite {
            name: name.clone().into(),
            text: format!(
                ".globl {name}\n.type {name},@function\n{name}:\n    ret\n.size {name}, .-{name}\n"
            ),
        };
        let threads = (0..8)
            .map(|_| {
                let site = site.clone();
                std::thread::spawn(move || try_materialize(&[site]))
            })
            .collect::<Vec<_>>();
        let addrs = threads
            .into_iter()
            .map(|thread| thread.join().unwrap().unwrap()[0])
            .collect::<Vec<_>>();
        assert!(addrs.iter().all(|addr| *addr == addrs[0]));
    }

    #[test]
    fn rewrite_syscall_text_hits_only_mnemonic_lines() {
        let mut src =
            "mov rax, 1\n    syscall\nsyscallx\n.byte 0x0f,0x05\n  syscall # c\nnop\n".to_string();
        assert!(super::rewrite_syscall_text(&mut src));
        assert_eq!(src.matches("mirvm_syscall_slot@GOTPCREL").count(), 2);
        assert_eq!(src.matches("call [r11]").count(), 2);
        assert!(src.contains("syscallx"));
        assert!(src.contains(".byte 0x0f,0x05"));
        assert!(src.contains("mirvm_syscall_slot: .quad 0"));
        let mut plain = "mov rax, 1\nsysenter\nint $0x80\n".to_string();
        assert!(!super::rewrite_syscall_text(&mut plain));
        assert!(!plain.contains("mirvm_syscall_slot"));
    }

    #[test]
    fn rewritten_syscall_stub_passthrough_and_register_discipline() {
        // A bare SYS_getpid syscall must pass through and return the real pid (non-zero). The
        // syscall leaves rbx intact, and the trampoline must preserve it the same way.
        let site = ir::AsmSite {
            name: "mirvm_asm_sc".into(),
            text: r#"
.globl mirvm_asm_sc
.type mirvm_asm_sc,@function
.section .text.mirvm_asm_sc,"ax",@progbits
mirvm_asm_sc:
    .intel_syntax noprefix
    mov rbx, 0x0123456789abcdef
    mov rax, 39
    syscall
    mov rcx, rbx
    mov QWORD PTR [rdi], rax
    mov QWORD PTR [rdi+8], rcx
    ret
    .att_syntax
.size mirvm_asm_sc, .-mirvm_asm_sc
.text
"#
            .to_owned(),
        };
        let addrs = try_materialize(&[site]).unwrap();
        let mut pair = [0u64; 2];
        let stub: unsafe extern "C" fn(*mut u8) = unsafe { std::mem::transmute(addrs[0]) };
        unsafe { stub((&mut pair as *mut u64).cast()) };
        assert_ne!(
            pair[0], 0,
            "SYS_getpid passthrough must return the real pid"
        );
        assert_eq!(pair[0] as i32, unsafe { libc::getpid() });
        assert_eq!(
            pair[1], 0x0123_4567_89ab_cdef,
            "rbx was not preserved under syscall discipline"
        );
    }
}
